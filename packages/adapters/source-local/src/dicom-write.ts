/** Minimal Part 10 Explicit VR Little Endian encoder; no pixel rewriting. */
export type TextVR = 'AE' | 'AS' | 'CS' | 'DA' | 'DS' | 'DT' | 'IS' | 'LO' | 'LT' | 'PN' | 'SH' | 'ST' | 'TM' | 'UC' | 'UI' | 'UR' | 'UT';
type NumericVR = 'US' | 'UL' | 'FL' | 'SL';
export interface DicomElement { readonly tag: number; readonly vr: TextVR | NumericVR | 'SQ' | 'OB'; readonly value: Uint8Array }
const LONG_VRS = new Set(['OB', 'SQ', 'UC', 'UR', 'UT']);
const UTF8 = new TextEncoder();

function concat(parts: readonly Uint8Array[]): Uint8Array {
  const result = new Uint8Array(parts.reduce((sum, part) => sum + part.length, 0));
  let offset = 0;
  for (const part of parts) { result.set(part, offset); offset += part.length; }
  return result;
}

export function text(tag: number, vr: TextVR, value: string): DicomElement {
  if (value.includes('\0')) throw new Error('DICOM text contains a NUL character');
  const raw = UTF8.encode(value);
  const padded = new Uint8Array(raw.length + raw.length % 2);
  padded.set(raw);
  if (raw.length % 2 && vr !== 'UI') padded[raw.length] = 32;
  return { tag, vr, value: padded };
}

export function numbers(tag: number, vr: NumericVR, values: readonly number[]): DicomElement {
  const value = new Uint8Array(values.length * (vr === 'US' ? 2 : 4));
  const view = new DataView(value.buffer);
  values.forEach((entry, index) => {
    if (!Number.isFinite(entry)) throw new Error('DICOM numeric value must be finite');
    if (vr === 'FL') {
      if (Math.abs(entry) > 3.4028234663852886e38) throw new Error('DICOM FL overflow');
      view.setFloat32(index * 4, entry, true); return;
    }
    const lower = vr === 'SL' ? -2147483648 : 0;
    const upper = vr === 'US' ? 65535 : vr === 'SL' ? 2147483647 : 4294967295;
    if (!Number.isInteger(entry) || entry < lower || entry > upper) throw new Error('DICOM integer out of range');
    if (vr === 'US') view.setUint16(index * 2, entry, true);
    else if (vr === 'SL') view.setInt32(index * 4, entry, true);
    else view.setUint32(index * 4, entry, true);
  });
  return { tag, vr, value };
}

function tagHeader(tag: number, length: number): Uint8Array {
  const header = new Uint8Array(8), view = new DataView(header.buffer);
  view.setUint16(0, Math.floor(tag / 65536), true);
  view.setUint16(2, tag % 65536, true);
  view.setUint32(4, length, true);
  return header;
}

export function sequence(tag: number, items: readonly (readonly DicomElement[])[]): DicomElement {
  const value = concat(items.map(item => {
    const encoded = encodeElements(item);
    return concat([tagHeader(0xfffee000, encoded.length), encoded]);
  }));
  return { tag, vr: 'SQ', value };
}

function encodeElement(element: DicomElement): Uint8Array {
  const { tag, vr, value } = element;
  if (!Number.isInteger(tag) || tag < 0 || tag > 0xffffffff || value.length % 2) throw new Error('Invalid DICOM element');
  const long = LONG_VRS.has(vr);
  if (!long && value.length > 65534) throw new Error('DICOM short VR value too long');
  const header = new Uint8Array(long ? 12 : 8), view = new DataView(header.buffer);
  view.setUint16(0, Math.floor(tag / 65536), true); view.setUint16(2, tag % 65536, true);
  header.set(UTF8.encode(vr), 4);
  if (long) view.setUint32(8, value.length, true); else view.setUint16(6, value.length, true);
  return concat([header, value]);
}

function encodeElements(elements: readonly DicomElement[]): Uint8Array {
  const sorted = [...elements].sort((a, b) => a.tag - b.tag);
  if (sorted.some((element, index) => element.tag === sorted[index - 1]?.tag)) throw new Error('Duplicate DICOM tag');
  return concat(sorted.map(encodeElement));
}

export function validUid(uid: string): boolean {
  return uid.length > 0 && uid.length <= 64 && /^(0|[1-9]\d*)(\.(0|[1-9]\d*))+$/u.test(uid);
}

export function encodePart10(elements: readonly DicomElement[], sopClassUid: string, sopInstanceUid: string): Uint8Array {
  if (![sopClassUid, sopInstanceUid].every(validUid)) throw new Error('Invalid SOP UID');
  if (elements.some(element => element.tag < 0x00080000)) throw new Error('File meta must be generated by encodePart10');
  const identity = elements.filter(element => element.tag === 0x00080016 || element.tag === 0x00080018);
  if (identity.length) throw new Error('SOP identity must be supplied to encodePart10');
  const meta = encodeElements([
    { tag: 0x00020001, vr: 'OB', value: new Uint8Array([0, 1]) },
    text(0x00020002, 'UI', sopClassUid), text(0x00020003, 'UI', sopInstanceUid),
    text(0x00020010, 'UI', '1.2.840.10008.1.2.1'),
    text(0x00020012, 'UI', '2.25.158713613967674338662605464620231001492'),
    text(0x00020013, 'SH', 'ODV_1'),
  ]);
  const preamble = new Uint8Array(132); preamble.set(UTF8.encode('DICM'), 128);
  return concat([preamble, encodeElement(numbers(0x00020000, 'UL', [meta.length])), meta,
    encodeElements([...elements, text(0x00080016, 'UI', sopClassUid), text(0x00080018, 'UI', sopInstanceUid)])]);
}

/** DICOM DS permits 16 ASCII characters, including sign and exponent. */
export function decimalString(value: number): string {
  if (!Number.isFinite(value)) throw new Error('DICOM 数值必须有限');
  if (String(value).length <= 16) return String(value);
  for (let precision = 15; precision >= 1; precision--) {
    const candidate = Number(value.toPrecision(precision)).toString();
    if (candidate.length <= 16) return candidate;
  }
  throw new Error('无法序列化 DICOM 数值');
}
